/**
 * scripts/generate-git-info.mjs
 *
 * Generates src/components/common/git-release/git-info.generated.ts
 * before TypeScript compilation runs.
 *
 * Priority order for data sources:
 *   1. Vercel build environment variables (VERCEL_GIT_COMMIT_SHA, etc.)
 *   2. Local git commands (git log / git rev-parse)
 *   3. Safe fallback — never shows "unknown"
 *
 * Run automatically via the "prebuild" npm script.
 * Also called by the Vite plugin's config() hook during `npm run dev`.
 */

import { execSync }  from 'child_process';
import { writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname }   from 'path';
import { fileURLToPath }      from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH  = resolve(__dirname, '../src/components/common/git-release/git-info.generated.ts');
const REPO_URL  = 'https://github.com/Pandi2352/react-vite-setup-2026';

// ─── Helper ──────────────────────────────────────────────────────────────────
const runGit = (cmd) => {
  try {
    return execSync(cmd, { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim() || null;
  } catch {
    return null;
  }
};

// ─── Source 1: Vercel environment variables ──────────────────────────────────
// Available on every Vercel build automatically.
const vercelHash   = process.env.VERCEL_GIT_COMMIT_SHA    || null;
const vercelMsg    = process.env.VERCEL_GIT_COMMIT_MESSAGE || null;
const vercelAuthor = process.env.VERCEL_GIT_COMMIT_AUTHOR_LOGIN || process.env.VERCEL_GIT_COMMIT_AUTHOR_NAME || null;
const vercelBranch = process.env.VERCEL_GIT_COMMIT_REF    || null;

// ─── Source 2: Local git commands ────────────────────────────────────────────
const gitHash   = runGit('git rev-parse HEAD');
const gitShort  = runGit('git rev-parse --short HEAD');
const gitDate   = runGit('git log -1 --format=%cd --date=format:"%Y-%m-%d %H:%M:%S %z"');
const gitMsg    = runGit('git log -1 --format=%s');
const gitAuthor = runGit('git log -1 --format=%an');
const gitBranch = runGit('git rev-parse --abbrev-ref HEAD');

// ─── Merge: Vercel vars win, git commands fill gaps ──────────────────────────
const commitHash   = vercelHash   || gitHash   || 'HEAD';
const commitShort  = vercelHash   ? vercelHash.slice(0, 7) : (gitShort || 'HEAD');
const commitDate   = gitDate      || new Date().toISOString().replace('T', ' ').slice(0, 19) + ' +0000';
const commitMsg    = vercelMsg    || gitMsg    || 'Latest commit';
const commitAuthor = vercelAuthor || gitAuthor || 'pandi';
const branch       = vercelBranch === 'HEAD' ? 'main' : (vercelBranch || gitBranch || 'main');

const info = {
  commitHash,
  commitShort,
  commitDate,
  commitMsg,
  commitAuthor,
  branch,
  repoUrl:   REPO_URL,
  commitUrl: `${REPO_URL}/commit/${commitShort}`,
};

// ─── Write file ───────────────────────────────────────────────────────────────
mkdirSync(dirname(OUT_PATH), { recursive: true });

const content = `// AUTO-GENERATED — do not edit by hand.
// Generated by scripts/generate-git-info.mjs on every dev start / CI build.
// Last generated: ${new Date().toISOString()}
import type { GitReleaseInfo } from './git-release.types';

const GIT_INFO: GitReleaseInfo = ${JSON.stringify(info, null, 2)};

export default GIT_INFO;
`;

writeFileSync(OUT_PATH, content, 'utf-8');

const source = vercelHash ? '(Vercel env vars)' : gitHash ? '(git commands)' : '(fallback)';
console.log(`\n[git-info] ✓ ${branch}@${commitShort} — ${commitDate} ${source}\n`);
